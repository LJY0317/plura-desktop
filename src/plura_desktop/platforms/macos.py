class MacOSPlatform(DesktopPlatform):
    @contextmanager
    def update_guard(self, layout: ProfileLayout):
        """Non-persistent, fail-closed writer lock on owned metadata directory.

        The lock is held only around derived app/selector reconciliation,
        never over the Desktop's lifetime. Directory locking avoids creating
        an untracked lock file that uninstall could mistake for foreign state.
        """
        import fcntl  # macOS-only; do not require fcntl on Windows

        folder = layout.metadata
        self.assert_safe_ancestry(folder)
        if self._is_linklike(folder) or not folder.is_dir() or not self.is_owned(folder):
            raise RuntimeError("Plura metadata directory is unsafe or missing")
        descriptor = os.open(
            folder,
            os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_CLOEXEC", 0),
        )
        try:
            identity = os.fstat(descriptor)
            current = folder.stat(follow_symlinks=False)
            if (identity.st_dev, identity.st_ino) != (current.st_dev, current.st_ino):
                raise RuntimeError("Plura metadata ownership changed during update lock")
            try:
                fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError as error:
                if error.errno in {errno.EAGAIN, errno.EWOULDBLOCK}:
                    raise RuntimeError(
                        "Another Plura profile refresh is already in progress; "
                        "retry after it finishes"
                    ) from error
                raise
            try:
                yield
            finally:
                fcntl.flock(descriptor, fcntl.LOCK_UN)
        finally:
            os.close(descriptor)

    def selector_health(self, layout: ProfileLayout) -> str:
        """Verify the *contents* of a managed launcher, not merely its .app folder.

        All paths are fixed Plura-owned metadata; no browser state, cookies,
        session JSONL, authentication, or remote records are read. Never follow
        a symlink or accept an unexpected executable/bundle identifier.
        """
        try:
            self.assert_safe_ancestry(layout.selector)
        except (OSError, RuntimeError):
            return "unsafe"
        selector = layout.selector
        if self._is_linklike(selector):
            return "unsafe"
        if not selector.exists():
            return "missing"
        if not selector.is_dir() or not self.is_owned(selector):
            return "unsafe"
        contents = selector / "Contents"
        if self._is_linklike(contents):
            return "unsafe"
        if not contents.is_dir():
            return "incomplete"
        if not self.is_owned(contents):
            return "unsafe"
        files = (
            contents / "Info.plist",
            contents / "MacOS/launcher",
            contents / "Resources/icon.icns",
        )
        for file in files:
            if self._is_linklike(file) or self._is_linklike(file.parent):
                return "unsafe"
            if not file.is_file():
                return "incomplete"
            if not self.is_owned(file):
                return "unsafe"
        try:
            # A launcher plist is small and exclusively generated by Plura.
            if files[0].stat().st_size > 32 * 1024:
                return "incomplete"
            with files[0].open("rb") as stream:
                info = plistlib.load(stream)
            if (
                not isinstance(info, dict)
                or info.get("CFBundleIdentifier") != layout.identifier
                or info.get("CFBundleExecutable") != "launcher"
                or info.get("CFBundlePackageType") != "APPL"
                or not os.access(files[1], os.X_OK)
                or files[2].stat().st_size == 0
            ):
                return "incomplete"
        except (OSError, ValueError, plistlib.InvalidFileException):
            return "incomplete"
        return "ready"

    def managed_runtime_health(self, layout: ProfileLayout) -> str:
        """Cheap structural check; cryptographic signature is verified on use."""
        root = self._profile_runtime_root(layout)
        try:
            self.assert_safe_ancestry(root)
        except (OSError, RuntimeError):
            return "unsafe"
        if self._is_linklike(root):
            return "unsafe"
        if not root.exists():
            return "missing"
        bundle = root / "ChatGPT.app"
        marker = self._runtime_marker(layout)
        files = (
            bundle / "Contents/Info.plist",
            bundle / "Contents/MacOS/ChatGPT",
            bundle / "Contents/Resources/app.asar",
            marker,
        )
        for path in (
            root, bundle, bundle / "Contents",
            bundle / "Contents/MacOS", bundle / "Contents/Resources",
        ):
            if self._is_linklike(path):
                return "unsafe"
            if not path.exists():
                return "incomplete"
            if not path.is_dir() or not self.is_owned(path):
                return "unsafe"
        for file in files:
            if self._is_linklike(file) or self._is_linklike(file.parent):
                return "unsafe"
            if not file.is_file():
                return "incomplete"
            if not self.is_owned(file):
                return "unsafe"
        return "ready"

    @staticmethod
    def _exchange_paths(left: Path, right: Path) -> None:
        """Atomically exchange two existing paths on macOS.

        The selector bundle's outer directory is a manifest-owned identity and must keep the same
        inode across refreshes. Swapping only its ``Contents`` directory gives LaunchServices a
        complete old-or-new bundle at all times while preserving that outer identity.
        """
        libc = ctypes.CDLL(None, use_errno=True)
        renamex_np = getattr(libc, "renamex_np", None)
        if renamex_np is None:
            raise RuntimeError("Atomic macOS selector exchange is unavailable")
        renamex_np.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint]
        renamex_np.restype = ctypes.c_int
        if renamex_np(os.fsencode(left), os.fsencode(right), RENAME_SWAP) != 0:
            error = ctypes.get_errno()
            raise OSError(error, os.strerror(error), f"{left} <-> {right}")

    platform_id = "macos"

    @staticmethod
    def _current_username() -> str:
        if not hasattr(os, "getuid"):
            raise RuntimeError("macOS user identity is unavailable on this platform")
        import pwd

        return pwd.getpwuid(os.getuid()).pw_name

